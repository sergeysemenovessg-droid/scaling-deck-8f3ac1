const curvePos = new THREE.CatmullRomCurve3(
  POS.map(p => new THREE.Vector3(...p)), false, 'centripetal', 0.5);
const curveLook = new THREE.CatmullRomCurve3(
  LOOK.map(p => new THREE.Vector3(...p)), false, 'centripetal', 0.5);

const _p = new THREE.Vector3(), _l = new THREE.Vector3();

/** позиция и цель камеры на доле маршрута t (0…1) */
export function cameraAt(t) {
  const u = Math.min(Math.max(t, 0), 1);
  curvePos.getPoint(u, _p);
  curveLook.getPoint(u, _l);
  return { pos: _p, look: _l };
}

/* ------------------------------------------------------------
   Что происходит в мире по ходу полёта.
   Отрезки подобраны под шоты: линия чертится чуть впереди камеры,
   чтобы зритель видел, как она возникает, а не находил готовой.
   ------------------------------------------------------------ */
const seg = (t, a, b) => Math.min(Math.max((t - a) / (b - a), 0), 1);
const ease = t => t * t * (3 - 2 * t);

export function worldAt(t) {
  return {
    axisX: 0.06 + 0.94 * ease(seg(t, 0.0, 0.27)),
    axisY: ease(seg(t, 0.275, 0.52)),
    axisZ: ease(seg(t, 0.525, 0.61)),
    axisF: ease(seg(t, 0.875, 0.975)),

    /* ветви развилок: каждая чертится перед тем, как камера до неё доедет */
    fork1: ease(seg(t, 0.145, 0.205)),
    fork2: ease(seg(t, 0.245, 0.305)),
    fork3: ease(seg(t, 0.395, 0.450)),
    fork4: ease(seg(t, 0.475, 0.530)),

    /* здание растёт этаж за этажом, спираль обвивает уже готовое */
    towerVisible: t > 0.515,
    built: ease(seg(t, 0.545, 0.735)),
    active: seg(t, 0.545, 0.735) * 5,
    spiral: ease(seg(t, 0.745, 0.885)),

    /* узлы */
    nodeZero: ease(seg(t, 0.0, 0.07)) * (1 - ease(seg(t, 0.36, 0.46))),
    nodeCorner: ease(seg(t, 0.28, 0.35)) * (1 - ease(seg(t, 0.60, 0.68))),
    nodeFinal: ease(seg(t, 0.905, 0.955)),

    /* отработавшее уходит, чтобы не висеть лишней диагональю в кадре */
    fadeX: 1 - ease(seg(t, 0.385, 0.455)),
    fadeY: 1 - ease(seg(t, 0.615, 0.695)),
    fadeZ: 1 - ease(seg(t, 0.90, 0.96)),
  };
}

